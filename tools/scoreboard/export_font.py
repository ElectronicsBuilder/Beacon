"""Export the firmware's 8x8 font (ScoreBoard/App/Matrix/FONT.c, ASCII8x8_Table)
to font8x8.py, so the GUI preview draws exactly what the matrix shows.

    python -m scoreboard.export_font
"""
from __future__ import annotations

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
FONT_C = HERE.parents[1] / "ScoreBoard" / "App" / "Matrix" / "FONT.c"
OUT = HERE / "font8x8.py"


def export() -> int:
    text = FONT_C.read_text(encoding="utf-8", errors="replace")
    m = re.search(r"ASCII8x8_Table\s*\[\s*\]\s*=\s*\{(.*?)\};", text, re.S)
    if not m:
        raise SystemExit("ASCII8x8_Table not found in " + str(FONT_C))
    body = re.sub(r"/\*.*?\*/|//[^\n]*", "", m.group(1), flags=re.S)
    values = [int(v, 16) for v in re.findall(r"0x[0-9a-fA-F]+", body)]
    chars = len(values) // 8
    lines = [
        '"""8x8 font from ScoreBoard/App/Matrix/FONT.c (generated by export_font.py, do not edit).',
        "",
        "FONT[c - 32] = 8 row bytes, bit 7 = leftmost pixel.",
        '"""',
        "FIRST = 32",
        "FONT = [",
    ]
    for c in range(chars):
        rows = ", ".join(f"0x{v:02X}" for v in values[c * 8:c * 8 + 8])
        ch = chr(32 + c)
        label = repr(ch) if ch not in "\\" else "'\\\\'"
        lines.append(f"    ({rows}),  # {label}")
    lines.append("]")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return chars


if __name__ == "__main__":
    n = export()
    print(f"{n} characters ({chr(32)!r}..{chr(31 + n)!r}) -> {OUT}")
